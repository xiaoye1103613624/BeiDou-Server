/* ===== 工具函数（与原掉落脚本通用） ===== */
function 读取时间() { return Math.ceil(new Date() / 1000); }

// 返回今天还能扫荡几次
function 剩余扫荡次数(bossObj) {
    var 基础 = bossObj.挑战限制;
    // 当天已用次数（用 getBossLog）
    var 已用 = cm.getPlayer().getBossLog(bossObj.挑战记录);
    // 当天扩充次数（用 getBossLog）
    var 扩充 = (bossObj.扩充Log === undefined)
              ? 0
              : cm.getPlayer().getBossLog(bossObj.扩充Log);
    return Math.max(0, 基础 + 扩充 - 已用);
}

function 转至邮件(itemId, itemName, qty) {
    var 倒计时 = 读取时间() + 60 * 60 * 24 * 存放时间;
    var sql = "INSERT INTO 泉哥_邮件 (玩家名称,角色id,倒计时,物品代码,物品名称,数量) VALUES ('" +
              cm.getPlayer().getName() + "'," + cm.getPlayer().getId() + "," +
              倒计时 + "," + itemId + ",'" + itemName + "'," + qty + ")";
    cm.getConnection().prepareStatement(sql).executeUpdate();
}

/* ===== 主流程 ===== */
function start() {
    var selStr = "#w#e#b一键扫荡 Boss 奖励.#k#n\r\n请选择要扫荡的 Boss.\r\n#r特别说明：此扫荡功能无奖励箱子发放.\r\n";
    var hasAny = false;                     // 有没有还能扫荡的 Boss

    for (var i = 0; i < 扫荡列表.length; i++) {
        var left = 剩余扫荡次数(扫荡列表[i]);
        if (left > 0) {                     // 次数用完的直接跳过
            hasAny = true;
            selStr += "#L" + i + "#" + 蓝箭头 + "#k" + extend(扫荡列表[i].名称) +
                      "  #r(一键扫荡剩余 " + left + " 次)#k#l\r\n";
        }
    }

    if (!hasAny) {                          // 全部 Boss 都 0 次
        cm.sendOk("#w#e#b当前境界副本，没有可扫荡的BOSS！#k#n");
        cm.dispose();
        return;
    }

    cm.sendSimple(selStr);
}

function action(mode, type, selection) {
    if (mode !== 1) {
        cm.dispose();
        return;
    }

    if (status === 0) {
        selected = selection;
        var boss = 扫荡列表[selected];
        var left = 剩余扫荡次数(boss);
        if (left <= 0) {
            cm.sendOk("今日「" + boss.名称 + "」扫荡次数已用完！");
            cm.dispose();
            return;
        }
        cm.sendYesNo("确定消耗 #r" + 扫荡价格 * left + "#k 个 #i" + 扫荡券 + "# 一键扫荡「" + boss.名称 + "」 #r" + left + " 次#k 吗？");
        status = 1;
    } else if (status === 1) {
        var boss = 扫荡列表[selected];

        /* 再次实时计算，防止并发 */
        var left = 剩余扫荡次数(boss);
        if (left <= 0) {
            cm.sendOk("今日「" + boss.名称 + "」扫荡次数已用完！");
            cm.dispose();
            return;
        }

        /* 检查扫荡券 */
        if (!cm.haveItem(扫荡券, 扫荡价格 * left)) {
            cm.sendOk("你的 #i" + 扫荡券 + "# 不足 " + 扫荡价格 * left + " 个！");
            cm.dispose();
            return;
        }
        cm.gainItem(扫荡券, -扫荡价格 * left);

        /* 开始掉落判定 */
        var mailFlag = false;
        var msg = "#d扫荡「" + boss.名称 + "」完成，获得以下奖励：\r\n";
        for (var i = 0; i < boss.公共奖项.length; i++) {
			var left = 剩余扫荡次数(boss);
            var prize = boss.公共奖项[i];
            if (Math.floor(Math.random() * 1000000) < prize.概率) {
                var qty = Math.floor(Math.random() * (prize.奖品.最高 - prize.奖品.最低 + 1)) + prize.奖品.最低;
                if (cm.canHold(prize.代码, qty)) {
                    cm.gainItem(prize.代码, qty * left);
                } else {
                    转至邮件(prize.代码, cm.getItemName(prize.代码), qty * left);
                    mailFlag = true;
                }
                msg += "#v" + prize.代码 + "# #b#z" + prize.代码 + "##r x " + qty * left + "#d\r\n";
            }
        }
        if (mailFlag) msg += "\r\n#r(背包已满，部分奖励已发邮件，" + 存放时间 + " 天内领取！)";
		
		var left = 剩余扫荡次数(boss);
        /* ⑤ 记录今日已扫荡次数 +1 */
		cm.getPlayer().setBossLog(boss.挑战记录, 0, left);
		cm.喇叭(3, "" + cm.getName() + ":扫荡「" + boss.名称 + "」，境界副本 " + left + " 次，获得大量奖励！");
        cm.sendOk(msg);
        cm.dispose();
    }
}

function realLength(str) {
    var len = 0;
    for (var i = 0; i < str.length; i++) {
        len += (str.charCodeAt(i) > 255 ? 2 : 1);
    }
    return len;
}

function extend(name) {
    var max = 8;                       // 总“半角”宽度
    var cur = realLength(name);
    while (cur < max) {
        name += " ";
        cur++;
    }
    return name;
}