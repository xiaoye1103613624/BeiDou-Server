function setItemPm(itemid){
	try{
		var next = false;
		var con = cm.getConnection()
		var ps = con.prepareStatement("select * from pmwp where itemid = "+itemid +"");
		var rs = ps.executeQuery()
		next = rs.next();
		rs.close()
		ps.close();
		if(!next){
			ps = con.prepareStatement("insert into pmwp values (?,?,?,?)");
			var cc = selectAll(itemid);
			ps.setInt(1,cc[2])
			ps.setInt(2,itemid)
			ps.setInt(3,0)
			ps.setString(4,cc[0])
			ps.executeUpdate()
			ps.close()
			deleteItem(itemid,cc[2])
		}
		con.close()
	}catch(ex){
		cm.playerMessage(ex)
	}
}
