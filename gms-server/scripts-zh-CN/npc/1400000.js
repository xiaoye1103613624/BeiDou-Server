function start() {
    status = -1;
    action(1, 0, 0);
}

function action(mode, type, selection) {
    if (mode == -1) {
        cm.dispose();
    } else {
        if (status >= 0 && mode == 0) {
            cm.sendOk("感谢你的光临！");
            cm.dispose();
            return;
        }
        if (mode == 1) {
            status++;
        } else {
            status--;
        }
        if (status == 0) {
            var text = "\r\n";
            text += "          " + 小彩虹 + "剪 刀 系 统     " + 小彩虹 + "\r\n\r\n";
            text += "\t#r将你的背包内第一格不可交易的装备变成可交易\r\n";
            text += "\t\t  部分道具无法使用，时装无法使用\r\n";
            text += "\t 请自行查看背包第一格是否是想要解锁的装备\r\n";
            text += "\t     每次使用本功能需要消耗#b1E#r冒险金币#k\r\n";
			text += "\t    #r部分特殊装备#b攻击力#r超过#b1000#r无法解锁#k\r\n";
            text += "              #L0#" + 蓝加 + "#e#r - 解锁 - " + 蓝加 + "#n#k#l\r\n\r\n";

            cm.sendSimple(text);

        } else if (status == 1) {
            var item = cm.getChar().getInventory(Packages.client.inventory.MapleInventoryType.EQUIP).getItem(1);
            if (cm.getMeso() < 金币所需) {
                cm.sendOk("金币不足1E");
                cm.dispose();
            } else if (item == null) {
                cm.sendOk("如果要解除不可交易的装备，请把物品放在背包第一格!");
                cm.dispose();
            } else if (cm.isCash(item.getItemId())) {
                cm.sendOk("#r#e点装不在此项服务范围.\r\n#n#b请换一个非点装,或选择点装服务");
                cm.dispose();
            } else {
                // 确保比较的类型一致
                var itemId = item.getItemId();
                if (不允许解锁的物品.indexOf(itemId) !== -1) { // 使用 indexOf 替代 includes
                    cm.sendOk("#r#e该物品不允许解锁。\r\n#n#b请换一个其他物品。");
                    cm.dispose();
                } else {
                    /* —— 新增：1113231 专属检测 —— */
                // 2. 需要检测攻击力的道具（想加多少就往里写）
                var 攻击力超限禁止列表 = [1113231, 1003172,1052314,1082295,1072485,1102275,1132143,1302355,1402268,1432227,1442285,1382273,1452266,1462252,1472275,1332289,1482232,1492245,1098006];   // ← 这里随意扩
                if (攻击力超限禁止列表.indexOf(itemId) !== -1) {
                    var watk = parseInt(item.getWatk() || 0);
                    if (watk > 1000) {
                        cm.sendOk("#r#e该装备攻击力超过 1000，禁止解锁！#k");
                        cm.dispose();
                        return;
                    }
                }
					/* —— 新增：1113231 专属检测 —— */
					
					item.setFlag(0);  //解锁
                    cm.gainMeso(-金币所需);
					var item = cm.getInventory(1).getItem(1);
					switch (item.getFlag()) {
					case 0: item.setFlag(16); break;
					case 8: item.setFlag(0); break;
					}
					cm.getPlayer().forceReAddItem_Flag(item.copy(), Packages.client.inventory.MapleInventoryType.EQUIP);
					cm.sendOk("#e#d装备变成可交易了哦！");
					cm.dispose();
                }
            }
        }
    }
}