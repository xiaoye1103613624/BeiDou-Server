function start() {
    status = -1;
    action(1, 0, 0);
}

function action(mode, type, selection) {
    if (mode == -1) {
        cm.dispose();
    } else {
        if (status >= 0 && mode == 0) {
            cm.dispose();
            return;
        }
        if (mode == 1) {
            status++;
        } else {
            status--;
        }

        if (status == 0) {
            var 当前地图ID = cm.getMapId();
            var 召唤信息 = 列表1[当前地图ID];
            if (召唤信息) {
                // 检查当前地图是否已经有怪物
                var monsters = cm.getMap().getAllMonstersThreadsafe();
                var monsterCount = monsters.size();
                if (monsterCount > 0) {
                    cm.sendOk("当前地图已经有怪物存在，无法召唤新的怪物。");
                    cm.dispose();
                } else {
                    // 如果当前地图没有怪物，弹出确认对话框
                    cm.sendYesNo("确定要在当前地图召唤怪物#r#e #o" + 召唤信息.怪物ID + "##k#n 吗？");
                }
            } else {
                // 如果当前地图ID不在列表中，提示无法召唤
                cm.sendOk("当前地图不支持召唤怪物功能。");
                cm.dispose();
            }
        } else if (status == 1) {
            if (selection == 1) { // 玩家点击了“否”
                cm.dispose(); // 结束对话
            } else {
                var 当前地图ID = cm.getMapId();
                var 召唤信息 = 列表1[当前地图ID];
                if (召唤信息) {
                    // 召唤怪物
                    for (var i = 0; i < 召唤信息.数量; i++) {
						cm.召唤怪物(召唤信息.怪物ID, 召唤信息.血量, 0, 1, 当前地图ID, 召唤信息.坐标X, 召唤信息.坐标Y);
				//		cm.召唤怪物(bossid, bossxl, bossjy, 1, fubendt, -782, -18);
                    }
                    cm.sendOk("已成功召唤怪物！");
					cm.dispose(); // 结束对话
                }
                cm.dispose(); // 结束对话
            }
        }
    }
}