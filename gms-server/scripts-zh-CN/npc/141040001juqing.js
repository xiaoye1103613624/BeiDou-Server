var status = -1;

function start() {
    status = -1;
    action(1, 0, 0);
}

function action(mode, type, selection) {
    if (mode < 0) {
        // 玩家跳过/关闭对话 — 仍然传送，避免卡图
		cm.forceStartQuest(32192);
        cm.warp(141040002, 0);
        cm.dispose();
        return;
    }
    status++;

    if (status === 0) {
        cm.sendNext("哎？你们突然一大帮人闯进来，要做什么？");
    } else if (status === 1) {
        cm.sendNext("#b#p1510000#：#k\r\n咳咳……嗯……咳咳。要从哪里说起好呢。");
    } else if (status === 2) {
        cm.sendNext("#b#p1510005#：#k\r\n那个嘛……嗯……");
    } else if (status === 3) {
        cm.sendNext("要说什么就快说！我正忙着要做饭！");
    } else if (status === 4) {
        cm.sendNext("#b#p1510002#：#k\r\n我是来道歉的。很抱歉之前误会了你。");
    } else if (status === 5) {
        cm.sendNext("#b#p1510003#：#k\r\n一切都是场误会。你不是魔女，你既没破坏冰川，也没害得海平面升高。反而还照顾了我们那些失去家园的孩子们。");
    } else if (status === 6) {
        cm.sendNext("哈，你明白得还真早啊。");
    } else if (status === 7) {
        cm.sendNext("#b#p1510000#：#k\r\n总之，真是很抱歉。你应该早点儿说清楚啊。要是那样的话，不就不会发生什么误会了嘛。");
    } else if (status === 8) {
        cm.sendNext("真是可笑。我怎么会伤害你们这些我数十年来照顾的孩子呢？");
    } else if (status === 9) {
        cm.sendNext("#b#p1510000#：#k\r\n啊……？");
    } else if (status === 10) {
        cm.sendNext("我不是这地方的人。在故乡失去丈夫和孩子后……我本不想活了。为了在临死前好好看看我喜欢的雪，才来到这里的。");
    } else if (status === 11) {
        cm.sendNext("可就在那时，我看见了在大海上漂浮的你们。");
    } else if (status === 12) {
        cm.sendNext("一群小家伙眼中带着求生欲望，紧紧抓着我的衣角……我忍不下心不管啊。所以就带回家，自己抚养喽。");
    } else {
		cm.forceStartQuest(32192);
        cm.warp(141040002, 0);
        cm.dispose();
    }
}
