function sqlSelect(sql) {
	if (rc == true) {
		var data = Packages.org.gms.util.DatabaseConnection;
		var con = data.getConnection();
	} else {
		var data = Packages.database.DBConPool;
		var con = data.getInstance().getDataSource().getConnection();
	}
	var ret = new Array();
	var ps = con.prepareStatement(sql);
	var rs = ps.executeQuery();
	var metaData = ps.getMetaData();
	while (rs.next()) {
		var rsdata = new java.util.HashMap();
		for (var j = 1; j <= metaData.getColumnCount(); j++) {
			columnLabel = metaData.getColumnLabel(j);
			rsdata.put(columnLabel, rs.getObject(columnLabel));
		}
		if (!rsdata.isEmpty()) {
			ret.push(rsdata);
		}
	}
	rs.close();
	ps.close();
	con.close();
	return ret;
}

