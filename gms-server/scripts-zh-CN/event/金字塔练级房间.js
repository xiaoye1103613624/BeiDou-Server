    em.setProperty("monsterIdx", 0);
    em.setProperty("state", "1");
    var eim = em.newInstance("金字塔练级房间");
    var map = eim.setInstanceMap(926010004);
    map.resetFully();
    
    eim.startEventTimer(1200000); // 进地图以后刷怪时间
    em.schedule("spawnMonsters", 600);
    
