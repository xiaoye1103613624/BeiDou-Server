function spawnMonsters() {
    var eim = em.getInstance("金字塔练级房间");
    var map = eim.getMapInstance(0);
    var monsterIdx = parseInt(em.getProperty("monsterIdx"));
    
    var winner = eim.getPlayers()[0];
    showMapLaba("                当前开始击杀第" + (monsterIdx + 1) + "层怪             ");
    
    for (var i = 0; i < monsters[monsterIdx].count; i++) {
        var mob = em.getMonster(monsters[monsterIdx].id);
        
        var modified = em.newMonsterStats();
        modified.setOExp(mob.getMobExp());
        modified.setOHp(monsters[monsterIdx].hp);
        modified.setOMp(mob.getMobMaxMp());
        mob.setOverrideStats(modified);
        
        eim.registerMonster(mob);
        map.spawnMonsterOnGroundBelow(mob, new java.awt.Point(0, 88));
    }
    
    em.setProperty("monsterIdx", monsterIdx + 1);
}

