function warpOut(eim) {
    var map = em.getChannelServer().getMapFactory().getMap(926010000);
    var iter = eim.getPlayers().iterator();
    while (iter.hasNext()) {
        var player = iter.next();
        player.changeMap(map, map.getPortal(0));
        eim.unregisterPlayer(player);
    }
    eim.dispose();
}

