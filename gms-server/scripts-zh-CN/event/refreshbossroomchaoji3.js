// ===== 3. 创建副本 =====
function setup(eim, partyId) {
    em.setProperty("state",  "1");
    em.setProperty("monsterIdx", "0");

    // 1. 创建实例
    eim = em.newInstance("refreshbossroomchaoji3");

    // 2. 准备地图
    var map = eim.setInstanceMap(924010000);
    map.resetFully();

    // 3. 计时
    eim.startEventTimer(3600000);   // 60 min

    // 4. 立即刷第一波（关键：同步调用）
    spawnMonsters(eim);

    return eim;
}

// ===== 4. 刷怪函数 =====
// 改成带参数，避免再查一次实例
function spawnMonsters(eim) {
    if (eim == null) return;

    var map = eim.getMapInstance(0);
    if (map == null) return;

    var idx   = parseInt(em.getProperty("monsterIdx"));
    if (idx >= monsters.length) return;

    // 地图横幅
    map.startMapEffect("当前开始击杀第 " + (idx + 1) + " 层怪", 5121007);

    // 刷指定数量怪物
    for (var i = 0; i < monsters[idx].count; i++) {
        var mob = em.getMonster(monsters[idx].id);
        var stat = em.newMonsterStats();
        stat.setOHp(monsters[idx].hp);
        stat.setOMp(mob.getMobMaxMp());
        stat.setOExp(mob.getMobExp());
        mob.setOverrideStats(stat);
        eim.registerMonster(mob);
        map.spawnMonsterOnGroundBelow(mob, new java.awt.Point(5, 111));
    }

    em.setProperty("monsterIdx", idx + 1);
}

// ===== 5. 玩家进入 =====
function playerEntry(eim, player) {
    var map = eim.getMapInstance(0);
    player.changeMap(map, map.getPortal(0));
    eim.broadcastPlayerMsg(6, "剩余时间：3600 秒");
    eim.schedule("warpOut", 3600 * 1000);
}

// ===== 6. 怪物全清后回调 =====
function allMonstersDead(eim) {
    var idx = parseInt(em.getProperty("monsterIdx"));
    var players = eim.getPlayers();   // 获取副本内所有玩家

    if (idx < monsters.length) {
        // 还有下一层：发个人提示
        for (var i = 0; i < players.length; i++) {
            players[i].dropMessage(6, "当前开始击杀第 " + (idx + 1) + " 层怪");
        }
        spawnMonsters(eim);
    } else {
        // 通关：发个人提示
        for (var i = 0; i < players.length; i++) {
            players[i].dropMessage(6, "全部挑战完成，30秒后将会自动回到自由市场");
        }
        eim.schedule("warpOut", 30000);
    }
}

