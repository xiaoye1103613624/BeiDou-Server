function start() {
    var mapId = im.getMapId();

    // 检查禁止地图
    for (var i = 0; i < FORBIDDEN_MAPS.length; i++) {
        if (mapId === FORBIDDEN_MAPS[i]) {
            im.getPlayer().dropMessage(5, "您当前所在的地图无法使用轮回石碑。");
            im.dispose();
            return;
        }
    }

    // 检查是否已有轮回石碑
    if (im.hasSamsaraStone()) {
        im.getPlayer().dropMessage(5, "当前地图已存在轮回石碑，请等待效果结束后再使用。");
        im.dispose();
        return;
    }

    // 检查是否持有道具
    if (!im.haveItem(ITEM_ID, 1)) {
        im.getPlayer().dropMessage(5, "你没有轮回石碑道具！");
        im.dispose();
        return;
    }

    // 扣除道具
    im.gainItem(ITEM_ID, -1);

    // 召唤轮回石碑（加速刷怪 + 生成视觉NPC）
    im.summonSamsaraStone(NPC_ID, DURATION_MINUTES, ACCEL_RATE);

    // 发送提示
    im.getPlayer().dropMessage(5, "轮回石碑已激活！怪物刷新速度提升，持续 " + DURATION_MINUTES + " 分钟。");

    im.dispose();
}
