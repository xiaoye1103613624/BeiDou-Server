/**
 * @description 如果是sendSelectLevel，那么会根据的选项自动路由到对应的level+selection方法
 */
function levelStart() {
    let text = "尊贵的冒险家，您想去哪里呢？\r\n";
	text += "#L2#城镇地图#l \t #L1#练级地图#l \t #L0#BOSS地图#l";
	text += "#L3#跳跳地图#l \t #L4#材料传送#l";
    cm.sendSelectLevel(text);
}

function level0() {
	let text = "#b";
    for (let i = 0; i < bossmaps.length; i++) {
       text += "#L" + i + "#" + bossmaps[i][2] + "#l\r\n";
    }
	cm.sendNextSelectLevel("Boss", text);
}

