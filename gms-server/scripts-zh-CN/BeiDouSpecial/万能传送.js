/**
 * @description 如果是sendSelectLevel，那么会根据的选项自动路由到对应的level+selection方法
 */
function levelStart() {
    let text = "尊贵的冒险家，您想去哪里呢？\r\n";
	text += "#L2#城镇地图#l \t #L1#练级地图#l \t #L0#BOSS地图#l\r\n";
	text += "#L5#精英BOSS#l \t #L3#跳跳地图#l \t #L4#材料传送#l";
    cm.sendSelectLevel(text);
}

function level0() {
	let text = "#b";
    for (let i = 0; i < bossmaps.length; i++) {
       text += "#L" + i + "#" + bossmaps[i][2] + "#l\r\n";
    }
	cm.sendNextSelectLevel("Boss", text);
}

function level1() {
	let text = "#b";
	for (let i = 0; i < monstermaps.length; i++) {
		let playerCount = cm.getPlayerCount(monstermaps[i][0]);
		let status = playerCount > 0 ? "#r【" + playerCount + "人】#k" : "#b【无人】#k";
		text += "#L" + i + "#" + monstermaps[i][2] + "  " + status + "#l\r\n";
	}
	cm.sendNextSelectLevel("LevelUp", text);
}
