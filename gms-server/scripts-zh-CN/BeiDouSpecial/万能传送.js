// 从地图标签文本中提取纯地图名（去掉颜色码和费用说明）
function getMapLabel(raw) {
	return String(raw).replace(/#[a-zA-Z]/g, "").replace(/（.*?）/g, "").replace(/\t.*/g, "").trim();
}
