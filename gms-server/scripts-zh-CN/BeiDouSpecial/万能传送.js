/**
 * @description 如果是sendSelectLevel，那么会根据玩家的选项自动路由到对应的level+selection方法
 */
function levelStart() {
	let text = `尊贵的 ${cm.getPlayer().getName()}，您想去哪里呢？\r\n`;
	text += `#L2#城镇地图#l\t#L1##r练级地图#k#l\t#L4#野外BOSS#l\t#L0#BOSS地图#l\r\n`;
	text += `#L3#活动跳跳坐牢地图#l\r\n`;
    cm.sendSelectLevel(text);
}

