function level4() {
	let text = "#b";
	for (let i = 0; i < materialmaps.length; i++) {
		text += "#L" + i + "##b" + materialmaps[i][3] + "#k #i" + materialmaps[i][2] + "# #r（消耗" + (materialmaps[i][1]) + "金币）#b#l\r\n";
	}
	cm.sendNextSelectLevel("Material", text);
}

function level5() {
	let text = "#b";
	for (let i = 0; i < elitebossmaps.length; i++) {
		let alive = cm.countAllMonstersOnMap(elitebossmaps[i][0]) > 0;
		let status = alive ? "#g【存活】#k" : "#r【死亡】#k";
		text += "#L" + i + "#" + elitebossmaps[i][2] + "  " + status + "#l\r\n";
	}
	cm.sendNextSelectLevel("Elite", text);
}

