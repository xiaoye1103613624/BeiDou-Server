var status = -1;
var currentTownIdx = -1;

function start() {
    status = -1;
    currentTownIdx = -1;
    action(1, 0, 0);
}

function action(mode, type, selection) {
    if (mode === -1) {
        if (currentTownIdx >= 0) {
            currentTownIdx = -1;
            status = -1;
            showMainMenu();
            return;
        }
        cm.dispose();
        return;
    }

    if (mode === 0) {
        cm.dispose();
        return;
    }

    status++;

    if (currentTownIdx === -1) {
        if (status === 0) {
            showMainMenu();
        } else {
            handleMainSelection(selection);
        }
    } else {
        // In town details view
        if (status === 0) {
            showTownDetails();
        } else {
            handleTownAction(selection);
        }
    }
}

// ===== 主菜单 =====

function showMainMenu() {
    var text = "#e#b=== 城镇任务手册 ===#k#n\r\n\r\n";
    text += "#r完成某个城镇的全部任务 = 10AP属性奖励#k\r\n\r\n";
    text += "请选择要查看的城镇：\r\n";

    for (var i = 0; i < towns.length; i++) {
        var town = towns[i];
        var questIds = getTownQuestIds(town);
        var total = questIds.length;
        var completed = countCompletedQuests(questIds);
        var pct = total > 0 ? Math.floor(completed / total * 100) : 0;
        var allDone = (completed >= total && total > 0);
        var icon = allDone ? "#g[完]#k " : "";
        text += "#L" + i + "#" + icon + "#b" + town.name + "#k (";
        text += completed + "/" + total + ", " + pct + "%)#l\r\n";
    }

    status = 0;
    cm.sendSimple(text);
}

function handleMainSelection(selection) {
    if (selection >= 0 && selection < towns.length) {
        currentTownIdx = selection;
        status = -1;
        showTownDetails();
    } else {
        cm.dispose();
    }
}

// ===== 城镇详情 =====

function showTownDetails() {
    var town = towns[currentTownIdx];
    var questIds = getTownQuestIds(town);
    var total = questIds.length;
    var completed = countCompletedQuests(questIds);
    var collection = loadCollection();

    var text = "#e#b" + town.name + "#k#n\r\n\r\n";
    text += "任务总数：#b" + total + "#k  已完成：#b" + completed + "#k\r\n";
    text += "#d" + "".padStart(26, "——") + "#k\r\n\r\n";

    // 分页显示任务列表(最多显示50个)
    var showCount = Math.min(total, 50);
    for (var i = 0; i < showCount; i++) {
        var qid = questIds[i];
        var status = cm.getQuestStatus(qid);
        var icon;
        if (status === 2) {
            icon = "#g[完成]#k";
        } else if (status === 1) {
            icon = "#b[进行中]#k";
        } else {
            icon = "[未开始]";
        }

        var questName = getQuestName(qid);
        text += icon + " #o" + qid + "# " + questName + "#k\r\n";
    }

    if (total > 50) {
        text += "\r\n... 还有 #r" + (total - 50) + "#k 个任务未显示\r\n";
    }

    text += "\r\n#d" + "".padStart(26, "——") + "#k\r\n";
    text += "#L0##r[返回主菜单]#l\r\n";

    if (completed >= total && total > 0 && !isTownClaimed(currentTownIdx, collection)) {
        text += "#L1##d[领取城镇完成奖励: 10AP]#l\r\n";
    }

    status = 1;
    cm.sendSimple(text);
}

function handleTownAction(selection) {
    var town = towns[currentTownIdx];
    var questIds = getTownQuestIds(town);
    var total = questIds.length;
    var completed = countCompletedQuests(questIds);
    var collection = loadCollection();

    if (selection === 0) {
        // 返回主菜单
        currentTownIdx = -1;
        status = -1;
        showMainMenu();
        return;
    } else if (selection === 1) {
        if (completed >= total && total > 0 && !isTownClaimed(currentTownIdx, collection)) {
            claimTownReward(currentTownIdx, collection);
            cm.getPlayer().gainAp(10, true);
            cm.sendOk("恭喜！完成了 #b" + town.name + "#k 所有城镇任务！\r\n获得 #r10点AP#k 属性奖励！");
        } else {
            cm.sendOk("该城镇的奖励已经领取过了，或者任务尚未全部完成。");
        }
        status = -1;
        showTownDetails();
    }
}

// ===== 辅助函数 =====

function getTownQuestIds(town) {
    var ids = [];
    for (var a = 0; a < town.areaCodes.length; a++) {
        var ac = town.areaCodes[a];
        var qlist = areaQuestMap[ac];
        if (qlist) {
            for (var i = 0; i < qlist.length; i++) {
                ids.push(qlist[i]);
            }
        }
    }
    return ids;
}

function countCompletedQuests(questIds) {
    var count = 0;
    for (var i = 0; i < questIds.length; i++) {
        if (cm.isQuestCompleted(questIds[i])) {
            count++;
        }
    }
    return count;
}

function getQuestName(qid) {
    try {
        var quest = Quest.getInstance(qid);
        if (quest != null) {
            var name = quest.getName();
            if (name != null && name !== "") {
                return name;
            }
        }
    } catch (e) {}
    return "#o" + qid + "#";
}

// ===== 数据持久化 =====

function loadCollection() {
    var data = cm.getCharacterExtendValue("townQuestCollection");
    if (data == null || data === "") {
        return { claimed: [] };
    }
    try {
        var c = JSON.parse(data);
        if (!c.claimed) c.claimed = [];
        return c;
    } catch (e) {
        return { claimed: [] };
    }
}

function saveCollection(data) {
    cm.saveOrUpdateCharacterExtendValue("townQuestCollection", JSON.stringify(data));
}

function isTownClaimed(townIdx, collection) {
    return collection.claimed.indexOf(String(townIdx)) >= 0;
}

function claimTownReward(townIdx, collection) {
    var key = String(townIdx);
    if (collection.claimed.indexOf(key) < 0) {
        collection.claimed.push(key);
    }
    saveCollection(collection);
}
