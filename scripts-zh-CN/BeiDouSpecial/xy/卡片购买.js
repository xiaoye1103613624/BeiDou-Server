var status = -1;

function start() {
	status = -1;
	action(1, 0, 0);
}

function action(mode, type, selection) {
	if (mode == 1) {
		status++;
	} else {
		if (status >= 0) {
			cm.dispose();
			return;
		}
		status--;
	}
	if (status == 0) {
		var selStr = "请选择您要购买的卡片：\r\n";
		for (var i = 0; i < list.length; i++) {
			selStr += "#L" + i + "##v" + list[i].代码 + ":##z" + list[i].代码 + "#  价格: #r" + list[i].价格 + "#k 余额#l\r\n";
		}
		cm.sendSimple(selStr);
	} else if (status == 1) {
		var selectedCard = list[selection];
		if (cm.getPlayer().getItemQuantity(selectedCard.代码, false) > 0) {
			cm.sendOk("您已经拥有这张卡片：#v" + selectedCard.代码 + ":##z" + selectedCard.代码 + "#，无法重复购买。\r\n#r请使用后再来！");
			cm.dispose();
			return;
		} 
		else if (cm.getPlayer().getmoney() < selectedCard.价格) {
			cm.sendOk("您的余额不足，无法购买该卡片。需要 #r" + selectedCard.价格 + "#k 余额。");
			cm.dispose();
			return;
		} 
		else if (cm.getInventory(2).isFull(1)) {
			cm.sendOk("请确认消耗栏位至少有1个空格！");
			cm.dispose();
			return;
		} 
		else {
			cm.getPlayer().setmoney(cm.getPlayer().getmoney() - selectedCard.价格);
			cm.getPlayer().setlpjf(cm.getPlayer().getlpjf() + selectedCard.价格);
			cm.gainItem(selectedCard.代码, 1);
			cm.sendOk("您成功购买了一张卡片：#v" + selectedCard.代码 + "#\r\n已扣除 #r" + selectedCard.价格 + "#k 余额！增加" + selectedCard.价格 +"累计");
			cm.dispose();
		}
	}
}