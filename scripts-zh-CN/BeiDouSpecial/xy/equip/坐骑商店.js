var status = 0;
var category = 0;

function start() {
    cm.sendSimple(
        "#b#l🐎 坐骑商店 - 北斗冒险岛#l#k\r\n\r\n" +
        "#r注意: 骑宠需先获得对应骑乘技能(任务/活动获取)#k\r\n" +
        "骑宠装备栏: #b装备窗→坐骑栏(-18位)#k\r\n" +
        "鞍具装备栏: #b装备窗→鞍具栏(-19位)#k\r\n\r\n" +
        "#L0##b基础坐骑#k (19种, 30w-200w金币)#l\r\n" +
        "#L1##b高级坐骑#k (21种, 50w-150w金币)#l\r\n" +
        "#L2##b稀有坐骑#k (18种, 200w-500w金币)#l\r\n" +
        "#L3##b骑宠鞍具#k (15种, 5w-10w金币)#l\r\n" +
        "#L4##r关闭对话#k#l"
    );
}

function action(mode, type, selection) {
    if (mode == -1) {
        cm.dispose();
        return;
    }

    if (mode == 1) {
        status++;
    } else {
        cm.dispose();
        return;
    }

    if (status == 1) {
        category = selection;
        switch (selection) {
            case 0:
                showMountList(basicMounts, "基础坐骑");
                break;
            case 1:
                showMountList(advancedMounts, "高级坐骑");
                break;
            case 2:
                showMountList(rareMounts, "稀有坐骑");
                break;
            case 3:
                showMountList(saddleItems, "骑宠鞍具");
                break;
            case 4:
                cm.sendOk("欢迎下次光临!");
                cm.dispose();
                break;
        }
    } else if (status == 2) {
        // 已选择具体道具
        var chosenList;
        switch (category) {
            case 0: chosenList = basicMounts; break;
            case 1: chosenList = advancedMounts; break;
            case 2: chosenList = rareMounts; break;
            case 3: chosenList = saddleItems; break;
            default: cm.dispose(); return;
        }

        var itemData = chosenList[selection];
        var itemId = itemData[0];
        var price = itemData[1];
        var itemName = itemData[2];

        if (cm.getMeso() < price) {
            cm.sendOk("金币不足! 需要 #b" + price.toLocaleString() + "金币#k，你只有 #r" + cm.getMeso().toLocaleString() + "金币#k。");
            cm.dispose();
            return;
        }

        if (!cm.canHold(itemId)) {
            cm.sendOk("背包已满! 请清理道具/装备/设置栏后再来。");
            cm.dispose();
            return;
        }

        cm.gainMeso(-price);
        cm.gainItem(itemId, 1);
        cm.sendOk("购买成功! 获得 #b#t" + itemId + "##k。\r\n请到装备窗的坐骑栏(-18位)装备后使用骑乘技能。");
        cm.dispose();
    }
}

function showMountList(list, title) {
    var text = "#b" + title + " 列表#k\r\n\r\n";
    for (var i = 0; i < list.length; i++) {
        var itemId = list[i][0];
        var price = list[i][1];
        var itemName = list[i][2];
        text += "#L" + i + "##b#t" + itemId + "##k - " + itemName + " (" + price.toLocaleString() + "金币)#l\r\n";
    }
    text += "\r\n#L" + list.length + "##r返回主菜单#k#l";
    cm.sendSimple(text);
}
