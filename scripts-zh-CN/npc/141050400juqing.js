var status = -1;

function start() {
    status = -1;
    action(1, 0, 0);
}

function action(mode, type, selection) {
    if (mode < 0) {
        // 玩家跳过/关闭对话 — 仍然传送，避免卡在地图上
        cm.warp(141050000, 0);
        cm.dispose();
        return;
    }
    status++;

    if (status === 0) {
        cm.sendNext("#b部下：#k\r\n提督大人，捣乱者越来越靠近了。");
    } else if (status === 1) {
        cm.sendNext("…………");
    } else if (status === 2) {
        cm.sendNext("#b部下：#k\r\n提督大人，你得快点做决定了。");
    } else if (status === 3) {
        cm.sendNext("各位，你们有没有见过生命即将消逝那一瞬间的情景？");
    } else if (status === 4) {
        cm.sendNext("#b部下：#k\r\n……呃？");
    } else if (status === 5) {
        cm.sendNext("我是见过无数遍了。我曾经见过许多战友在我的臂弯里死去。");
    } else if (status === 6) {
        cm.sendNext("在濒死的瞬间，人类和动物是一样的。在断气之前，他们的身体簌簌发抖，望着映入眼中的最后景象，仿佛要抓住最后一丝生命的希望。");
    } else if (status === 7) {
        cm.sendNext("可是最终，那恳切的眼神会逐渐黯去，曾经温暖的身体也会变得冰冷。讽刺的是，在临终的那一瞬间，却带有某种崇高的美感，即使在那之后，只剩下沉寂。");
    } else if (status === 8) {
        cm.sendNext("……看来是时候离开这里了。");
    } else if (status === 9) {
        cm.sendNext("我们已经向敌人泄漏了很多信息了。不能再让敌人打探到任何重要信息。我给你10分钟。你去把证物全部销毁，然后离开这里。听明白了吗？");
    } else if (status === 10) {
        cm.sendNext("#b部下：#k\r\n是，提督大人！");
    } else if (status === 11) {
        cm.sendNext("我们已经获取了足够的资源。你去给那帮家伙留个深刻印象吧。");
    } else if (status === 12) {
        cm.sendNext("#b部下：#k\r\n就交给我去办吧。那帮家伙会迎来#r盖奥勒克#k的。#r盖奥勒克#k能毁坏的东西可不只有冰川。");
    } else if (status === 13) {
        cm.sendNext("……一帮蠢货。他们再怎么顽抗也是没用的。他们的末日就要到了。");
    } else {
        cm.warp(141050000, 0);
        cm.dispose();
    }
}
